// From the Nix AST to a Rust module. The shape of the output is the shape
// of the input: a Nix lambda is a closure, a let is a block of `let`
// statements, an attribute set is a builder, and laziness is spelled out
// where Nix has it implicitly, as `nix::thunk(move || ...)` around the
// expressions Nix would thunk and `nix::force(&x)?` where it would force.
//
// Two kinds of positions matter. In a strict position the code produces a
// value in weak head normal form (a function body, an operand, a
// condition). In a lazy position (an attribute value, a list element, a
// call argument, a let binding) it may produce a thunk. strict() and lazy()
// are the two entry points, and what gets thunked follows Nix's
// Expr::maybeThunk: literals, variables and lambdas never are.
//
// Every emitted expression has type `nix::Value` and appears where `?`
// can propagate a `nix::Result`: a module's value() or a closure.
//
// Closures own what they use. A `move` closure is preceded by clones of
// exactly the variables it refers to from outside, which the emitter
// records as it resolves names (`frames`), so the output reads
// `{ let x = x.clone(); move || ... }`. Recursive bindings (let, rec,
// formals' defaults) are declared as blank cells first and given their
// definitions afterwards, so every sibling can capture every other.

use std::collections::{BTreeSet, HashMap};

use crate::ast::*;
use crate::builtins_table::{arity_of, is_global, rust_fn_name};
use crate::lexer::SyntaxError;

pub struct Emitted {
    pub rust: String,
    // Files imported with a literal path, which must be compiled too.
    pub imports: Vec<String>,
}

pub fn emit_module(expr: &Expr, file: &str) -> Result<Emitted, SyntaxError> {
    let dir = match file.rfind('/') {
        Some(0) | None => "/".to_string(),
        Some(i) => file[..i].to_string(),
    };
    let mut e = Emitter {
        file: file.to_string(),
        dir,
        scopes: vec![Scope::default()],
        live: HashMap::new(),
        frames: Vec::new(),
        statics: Vec::new(),
        formals_count: 0,
        imports: Vec::new(),
    };
    let body = e.strict(expr)?;
    let mut out = String::new();
    out.push_str(&format!(
        "// Generated by jinx from {file}. Do not edit.\n\n"
    ));
    out.push_str("use jinx_runtime as nix;\n\n");
    out.push_str(&format!("const FILE: &str = {};\n", lit(file)));
    out.push_str(&format!("const DIR: &str = {};\n", lit(&e.dir)));
    for s in &e.statics {
        out.push_str(s);
        out.push('\n');
    }
    out.push_str("\npub fn value() -> nix::Result<nix::Value> {\n");
    out.push_str(&format!("    Ok({body})\n}}\n"));
    Ok(Emitted {
        rust: out,
        imports: e.imports,
    })
}

// A Rust string literal.
fn lit(s: &str) -> String {
    format!("{s:?}")
}

#[derive(Clone)]
struct Var {
    rust: String,
    // Whether the variable holds a value in weak head normal form, so that
    // reading it strictly needs no force.
    whnf: bool,
}

#[derive(Default)]
struct Scope {
    vars: HashMap<String, Var>,
    // The variable holding this scope's WithScope, when it is a `with`.
    with_var: Option<String>,
}

enum Resolution {
    Lexical(Var),
    With(String),
    Global,
}

struct Emitter {
    file: String,
    dir: String,
    scopes: Vec<Scope>,
    // Every Rust variable in scope, and the index of the scope declaring it.
    live: HashMap<String, usize>,
    // One per closure being emitted: the scope depth it starts at, and the
    // outer variables it refers to.
    frames: Vec<(usize, BTreeSet<String>)>,
    statics: Vec<String>,
    formals_count: usize,
    imports: Vec<String>,
}

type R = Result<String, SyntaxError>;

const RUST_KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
    "self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where",
    "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen", "union",
];

// A Nix identifier as a Rust one. `-` and `'` are legal in Nix and not in
// Rust; a quoted binding like `"texlive.infra" = ...` in a rec set can
// hold anything, and every other character becomes `_x` and its hex code.
// Names the emitter's own temporaries use (`j_`) and names that would read
// as a pattern (a leading capital) get a `v_` prefix.
fn mangle(name: &str) -> String {
    let mut s = String::new();
    for c in name.chars() {
        if c.is_ascii_alphanumeric() || c == '_' {
            s.push(c);
        } else if c == '-' {
            s.push('_');
        } else if c == '\'' {
            s.push_str("_p");
        } else {
            s.push_str(&format!("_x{:x}", c as u32));
        }
    }
    let first = s.chars().next();
    if s.is_empty()
        || s == "_"
        || first.is_some_and(|c| c.is_ascii_digit() || c.is_ascii_uppercase())
        || s.starts_with("j_")
        || s.starts_with("v_")
    {
        s = format!("v_{s}");
    }
    if RUST_KEYWORDS.contains(&s.as_str()) {
        s.push('_');
    }
    s
}

impl Emitter {
    fn fail<T>(&self, message: impl Into<String>, pos: &Pos) -> Result<T, SyntaxError> {
        Err(SyntaxError {
            message: message.into(),
            pos: pos.clone(),
        })
    }

    fn where_(&self, pos: &Pos) -> String {
        lit(&format!("{}:{}:{}", self.file, pos.line, pos.column))
    }

    // ---- scopes -------------------------------------------------------------

    fn push_scope(&mut self) {
        self.scopes.push(Scope::default());
    }

    fn pop_scope(&mut self) {
        let depth = self.scopes.len() - 1;
        self.live.retain(|_, d| *d != depth);
        self.scopes.pop();
    }

    // A Rust name no enclosing scope uses, so `let x = 1; in let x = x +
    // 1; in x` gets x and x_1.
    fn fresh(&mut self, base: &str) -> String {
        let mut name = base.to_string();
        let mut i = 1;
        while self.live.contains_key(&name) {
            name = format!("{base}_{i}");
            i += 1;
        }
        self.live.insert(name.clone(), self.scopes.len() - 1);
        name
    }

    fn declare(&mut self, nix_name: &str, whnf: bool) -> String {
        let rust = self.fresh(&mangle(nix_name));
        let var = Var {
            rust: rust.clone(),
            whnf,
        };
        self.scopes
            .last_mut()
            .unwrap()
            .vars
            .insert(nix_name.to_string(), var);
        rust
    }

    // A Rust-only temporary (a with-scope, an argument set).
    fn temp(&mut self, base: &str) -> String {
        self.fresh(&format!("j_{base}"))
    }

    // Record that the code being emitted refers to a Rust variable, so
    // every closure between here and its declaration clones it.
    fn use_var(&mut self, rust: &str) -> String {
        if let Some(&depth) = self.live.get(rust) {
            for (start, caps) in self.frames.iter_mut() {
                if depth < *start {
                    caps.insert(rust.to_string());
                }
            }
        }
        rust.to_string()
    }

    fn resolve(&self, name: &str) -> Resolution {
        let mut with = None;
        for s in self.scopes.iter().rev() {
            if let Some(v) = s.vars.get(name) {
                return Resolution::Lexical(v.clone());
            }
            if with.is_none() {
                with = s.with_var.clone();
            }
        }
        match with {
            Some(w) => Resolution::With(w),
            None => Resolution::Global,
        }
    }

    fn innermost_with(&self) -> Option<String> {
        self.scopes.iter().rev().find_map(|s| s.with_var.clone())
    }

    // A `move` closure with the given parameters, whose body `body` emits.
    fn closure(&mut self, params: &str, body: impl FnOnce(&mut Self) -> R) -> R {
        self.frames.push((self.scopes.len(), BTreeSet::new()));
        let b = body(self);
        let (_, caps) = self.frames.pop().unwrap();
        Ok(with_clones(&caps, format!("move |{params}| {}", b?)))
    }

    fn thunk(&mut self, body: impl FnOnce(&mut Self) -> R) -> R {
        let c = self.closure("", |em| Ok(format!("Ok({})", body(em)?)))?;
        Ok(format!("nix::thunk({c})"))
    }

    // ---- the two entry points -----------------------------------------------

    // A Value that may be a thunk: the expression itself when Nix would
    // not thunk it, a thunk otherwise.
    fn lazy(&mut self, e: &Expr) -> R {
        match &e.kind {
            ExprKind::Var(name) => return self.var_lazy(name, &e.pos),
            ExprKind::Int(_) | ExprKind::Float(_) | ExprKind::Lambda { .. } => {
                return self.strict(e)
            }
            ExprKind::Str(parts) if all_literal(parts).is_some() => return self.strict(e),
            ExprKind::List(xs) if xs.is_empty() => return self.strict(e),
            _ => {}
        }
        self.thunk(|em| em.strict(e))
    }

    // A Value in weak head normal form.
    fn strict(&mut self, e: &Expr) -> R {
        match &e.kind {
            ExprKind::Var(name) => self.var_strict(name, &e.pos),
            ExprKind::Int(i) => Ok(format!("nix::int({i})")),
            ExprKind::Float(f) => Ok(float_literal(*f)),
            ExprKind::Str(parts) => self.string(parts),
            ExprKind::Path(anchor, parts) => self.path(*anchor, parts),
            ExprKind::List(xs) => {
                let items = xs
                    .iter()
                    .map(|x| self.lazy(x))
                    .collect::<Result<Vec<_>, _>>()?;
                Ok(format!("nix::list(vec![{}])", items.join(", ")))
            }
            ExprKind::Attrs {
                recursive,
                bindings,
            } => {
                if *recursive {
                    self.rec_attrs(bindings)
                } else {
                    self.attrs(bindings)
                }
            }
            ExprKind::Select {
                subject,
                path,
                fallback,
            } => self.select(subject, path, fallback.as_deref()),
            ExprKind::HasAttr { subject, path } => {
                let s = self.operand(subject)?;
                let p = self.attr_path(path)?;
                Ok(format!("nix::bool(nix::has(&{s}, &[{p}])?)"))
            }
            ExprKind::Lambda {
                param,
                formals,
                body,
            } => self.lambda(param.as_deref(), formals.as_ref(), body),
            ExprKind::Call { .. } => self.call(e),
            ExprKind::Let { bindings, body } => {
                self.push_scope();
                let r = (|| {
                    let mut stmts = String::new();
                    self.declare_group(bindings, &mut stmts, false)?;
                    let b = self.strict(body)?;
                    Ok(format!("{{\n{stmts}{b}\n}}"))
                })();
                self.pop_scope();
                r
            }
            ExprKind::With { scope, body } => {
                let outer = self.innermost_with().map(|w| self.use_var(&w));
                let set = self.lazy(scope)?;
                self.push_scope();
                let w = self.temp("w");
                self.scopes.last_mut().unwrap().with_var = Some(w.clone());
                let outer = match outer {
                    Some(o) => format!("Some(&{o})"),
                    None => "None".into(),
                };
                let r = self.strict(body);
                self.pop_scope();
                Ok(format!(
                    "{{\nlet {w} = nix::with_scope({set}, {outer});\n{}\n}}",
                    r?
                ))
            }
            ExprKind::Assert { condition, body } => {
                let c = self.operand(condition)?;
                let at = self.where_(&e.pos);
                let b = self.strict(body)?;
                Ok(format!("{{\nnix::assert(&{c}, {at})?;\n{b}\n}}"))
            }
            ExprKind::If {
                condition,
                then,
                otherwise,
            } => {
                let c = self.operand(condition)?;
                let t = self.strict(then)?;
                let o = self.strict(otherwise)?;
                Ok(format!("if nix::as_bool(&{c})? {{ {t} }} else {{ {o} }}"))
            }
            ExprKind::Unary(op, operand) => {
                let x = self.operand(operand)?;
                Ok(match op {
                    UnaryOp::Not => format!("nix::not(&{x})?"),
                    UnaryOp::Neg => format!("nix::neg(&{x})?"),
                })
            }
            ExprKind::Binary(op, l, r) => self.binary(*op, l, r),
        }
    }

    // An operand of an operator or a subject of a selection: the runtime
    // forces it, so a variable is passed as it is and anything else
    // strictly.
    fn operand(&mut self, e: &Expr) -> R {
        if let ExprKind::Var(name) = &e.kind {
            if let Resolution::With(w) = self.resolve(name) {
                if !is_global(name) {
                    let w = self.use_var(&w);
                    return Ok(format!("nix::lookup(&{w}, {})?", lit(name)));
                }
            }
            if let (Resolution::Lexical(v), false) = (self.resolve(name), name == "__curPos") {
                return Ok(self.use_var(&v.rust));
            }
            return self.var_lazy(name, &e.pos);
        }
        self.strict(e)
    }

    // ---- variables ----------------------------------------------------------

    fn var_lazy(&mut self, name: &str, pos: &Pos) -> R {
        // `__curPos` is syntax, whatever binds the name.
        if name == "__curPos" {
            return self.global(name, pos);
        }
        match self.resolve(name) {
            Resolution::Lexical(v) => {
                let r = self.use_var(&v.rust);
                Ok(format!("{r}.clone()"))
            }
            // Globals are bound in Nix's base environment, which is
            // lexical, so `with { map = 1; }; map` is still builtins.map.
            Resolution::With(_) if is_global(name) => self.global(name, pos),
            // A with-bound variable is a lookup in a set that may not be
            // evaluable yet, so in a lazy position it is a thunk, as in Nix.
            Resolution::With(w) => self.thunk(|em| {
                let w = em.use_var(&w);
                Ok(format!("nix::lookup(&{w}, {})?", lit(name)))
            }),
            Resolution::Global => self.global(name, pos),
        }
    }

    fn var_strict(&mut self, name: &str, pos: &Pos) -> R {
        if name == "__curPos" {
            return self.global(name, pos);
        }
        match self.resolve(name) {
            Resolution::Lexical(v) => {
                let r = self.use_var(&v.rust);
                Ok(if v.whnf {
                    format!("{r}.clone()")
                } else {
                    format!("nix::force(&{r})?")
                })
            }
            Resolution::With(_) if is_global(name) => self.global(name, pos),
            Resolution::With(w) => {
                let w = self.use_var(&w);
                Ok(format!("nix::force(&nix::lookup(&{w}, {})?)?", lit(name)))
            }
            Resolution::Global => self.global(name, pos),
        }
    }

    // A free variable: one of Nix's globals, or `__name` for builtins.name.
    fn global(&mut self, name: &str, pos: &Pos) -> R {
        match name {
            "true" => return Ok("nix::bool(true)".into()),
            "false" => return Ok("nix::bool(false)".into()),
            "null" => return Ok("nix::null()".into()),
            "builtins" => return Ok("nix::builtins()".into()),
            "__curPos" => return Ok(format!("nix::cur_pos(FILE, {}, {})", pos.line, pos.column)),
            _ => {}
        }
        match global_builtin(name) {
            Some(b) => Ok(format!("nix::builtins::get({})", lit(b))),
            None => self.fail(format!("undefined variable '{name}'"), pos),
        }
    }

    // ---- literals -----------------------------------------------------------

    fn string(&mut self, parts: &[StrPart]) -> R {
        if let Some(s) = all_literal(parts) {
            return Ok(format!("nix::str_lit({})", lit(&s)));
        }
        let mut out = String::from("{ let mut j_s = nix::StrBuilder::new(); ");
        for p in parts {
            match p {
                StrPart::Lit(t) => out.push_str(&format!("j_s.lit({}); ", lit(t))),
                StrPart::Expr(e) => {
                    let v = self.operand(e)?;
                    out.push_str(&format!("j_s.val(&{v})?; "));
                }
            }
        }
        out.push_str("j_s.finish() }");
        Ok(out)
    }

    fn path(&mut self, anchor: PathAnchor, parts: &[StrPart]) -> R {
        if let Some(text) = all_literal(parts) {
            if text.ends_with(".nix") {
                self.note_path(anchor, text);
            }
        }
        if anchor == PathAnchor::Search {
            let name = all_literal(parts).unwrap_or_default();
            return Ok(format!(
                "nix::b::findFile(&[nix::list(vec![]), nix::str_lit({})])?",
                lit(&name)
            ));
        }
        let mut out = String::from("{ let mut j_p = nix::PathBuilder::new(DIR); ");
        for p in parts {
            match p {
                StrPart::Lit(t) => out.push_str(&format!("j_p.lit({}); ", lit(t))),
                StrPart::Expr(e) => {
                    let v = self.operand(e)?;
                    out.push_str(&format!("j_p.val(&{v})?; "));
                }
            }
        }
        out.push_str("j_p.finish()? }");
        Ok(out)
    }

    // ---- attribute sets -----------------------------------------------------

    fn attrs(&mut self, bindings: &[Binding]) -> R {
        if bindings.is_empty() {
            return Ok("nix::attrs(nix::Attrs::new())".into());
        }
        // `inherit (e) a b;` evaluates e once, in a variable of its own.
        let mut pre = String::new();
        let mut from_vars: Vec<(*const Expr, String)> = Vec::new();
        let mut sets = String::new();
        self.push_scope();
        let r = (|| {
            for b in bindings {
                let value = match b.inherited {
                    Inherited::No => {
                        // The values are in the enclosing scope; the pushed
                        // scope only holds the temporaries.
                        self.lazy(&b.value)?
                    }
                    Inherited::Scope => {
                        let ExprKind::Var(n) = &b.value.kind else {
                            unreachable!()
                        };
                        self.var_lazy(n, &b.value.pos)?
                    }
                    Inherited::From => self.inherit_from(b, &mut pre, &mut from_vars)?,
                };
                match &b.name {
                    AttrName::Static { name, pos } => sets.push_str(&format!(
                        "j_m.set({}, {}, {}, {value});\n",
                        lit(name),
                        pos.line,
                        pos.column
                    )),
                    AttrName::Dynamic { expr, .. } => {
                        let n = self.strict(expr)?;
                        sets.push_str(&format!("j_m.dynamic({n}, {value})?;\n"));
                    }
                }
            }
            Ok(())
        })();
        self.pop_scope();
        r?;
        Ok(format!(
            "{{\n{pre}let mut j_m = nix::AttrsBuilder::new(FILE);\n{sets}j_m.build()\n}}"
        ))
    }

    // `inherit (e) x`: a thunk selecting x from e, made once per e. The
    // set is selected from only when the attribute is forced, which is what
    // lets `inherit (self) x` appear inside the fixpoint that defines self.
    fn inherit_from(
        &mut self,
        b: &Binding,
        pre: &mut String,
        from_vars: &mut Vec<(*const Expr, String)>,
    ) -> R {
        let ExprKind::Select { subject, path, .. } = &b.value.kind else {
            unreachable!("inherit-from is a selection")
        };
        let name = path[0].static_name().expect("static inherit");
        let key: *const Expr = &**subject;
        let from = match from_vars.iter().find(|(k, _)| *k == key) {
            Some((_, v)) => v.clone(),
            None => {
                let v = self.temp("from");
                let value = self.lazy(subject)?;
                pre.push_str(&format!("let {v} = {value};\n"));
                from_vars.push((key, v.clone()));
                v
            }
        };
        self.thunk(|em| {
            let f = em.use_var(&from);
            Ok(format!("nix::attr(&{f}, {})?", lit(name)))
        })
    }

    // `rec { ... }`: every attribute becomes a variable the others can see,
    // then the builder collects them.
    fn rec_attrs(&mut self, bindings: &[Binding]) -> R {
        self.push_scope();
        let r = (|| {
            let mut stmts = String::new();
            let overrides = bindings
                .iter()
                .any(|b| b.name.static_name() == Some("__overrides"));
            let declared = self.declare_group(bindings, &mut stmts, overrides)?;
            let mut sets = String::new();
            for b in bindings {
                match &b.name {
                    AttrName::Static { name, pos } => {
                        let v = self.use_var(&declared[name.as_str()]);
                        sets.push_str(&format!(
                            "j_m.set({}, {}, {}, {v}.clone());\n",
                            lit(name),
                            pos.line,
                            pos.column
                        ));
                    }
                    // Dynamic names are evaluated in the rec scope, as Nix
                    // does.
                    AttrName::Dynamic { expr, .. } => {
                        let n = self.strict(expr)?;
                        let v = self.lazy(&b.value)?;
                        sets.push_str(&format!("j_m.dynamic({n}, {v})?;\n"));
                    }
                }
            }
            let mut build = "j_m.build()".to_string();
            if let Some(o) = declared.get("__overrides") {
                let o = self.use_var(o);
                let cells: Vec<String> = declared
                    .iter()
                    .filter(|(n, _)| *n != "__overrides")
                    .collect::<std::collections::BTreeMap<_, _>>()
                    .into_iter()
                    .map(|(n, v)| format!("({}, &{v})", lit(n)))
                    .collect();
                build = format!(
                    "nix::rec_overrides({build}, &[{}], &{o})?",
                    cells.join(", ")
                );
            }
            Ok(format!(
                "{{\n{stmts}let mut j_m = nix::AttrsBuilder::new(FILE);\n{sets}{build}\n}}"
            ))
        })();
        self.pop_scope();
        r
    }

    // Declare the static bindings of a let or rec in the current scope, as
    // statements appended to `stmts`. Literals are plain values; everything
    // else is a blank cell first, defined once all are declared, so any
    // binding can refer to any other.
    // With `all_cells`, literals get cells too, so they can be redefined
    // (`__overrides`).
    fn declare_group(
        &mut self,
        bindings: &[Binding],
        stmts: &mut String,
        all_cells: bool,
    ) -> Result<HashMap<String, String>, SyntaxError> {
        let mut declared = HashMap::new();
        let mut cells = Vec::new();
        for b in bindings {
            let Some(name) = b.name.static_name() else {
                continue;
            };
            if b.inherited == Inherited::No && is_literal(&b.value) && !all_cells {
                let v = self.strict(&b.value)?;
                let rust = self.declare(name, true);
                stmts.push_str(&format!("let {rust} = {v};\n"));
                declared.insert(name.to_string(), rust);
            } else if b.inherited == Inherited::Scope {
                // `inherit x;` reads the enclosing scope, before the group's
                // own names shadow it.
                let ExprKind::Var(n) = &b.value.kind else {
                    unreachable!()
                };
                let v = self.var_lazy(n, &b.value.pos)?;
                let rust = self.fresh(&mangle(name));
                stmts.push_str(&format!("let {rust} = {v};\n"));
                cells.push((b, Some(rust.clone())));
                declared.insert(name.to_string(), rust);
            } else {
                cells.push((b, None));
            }
        }
        // Bind the inherited names only now, so `inherit x;` above saw the
        // outer x.
        for (b, rust) in &cells {
            if let Some(rust) = rust {
                let name = b.name.static_name().unwrap();
                let var = Var {
                    rust: rust.clone(),
                    whnf: false,
                };
                self.scopes
                    .last_mut()
                    .unwrap()
                    .vars
                    .insert(name.to_string(), var);
            }
        }
        let mut blanks = Vec::new();
        for (b, rust) in &cells {
            if rust.is_none() {
                let name = b.name.static_name().unwrap();
                let rust = self.declare(name, false);
                stmts.push_str(&format!("let {rust} = nix::blank();\n"));
                declared.insert(name.to_string(), rust.clone());
                blanks.push((*b, rust));
            }
        }
        let mut pre = String::new();
        let mut from_vars = Vec::new();
        let mut inits = String::new();
        for (b, rust) in blanks {
            let init = match (&b.inherited, &b.value.kind) {
                (Inherited::From, _) => {
                    let t = self.inherit_from(b, &mut pre, &mut from_vars)?;
                    format!("nix::init_value(&{rust}, {t});\n")
                }
                (_, ExprKind::Lambda { .. } | ExprKind::Var(_)) => {
                    let v = self.lazy(&b.value)?;
                    format!("nix::init_value(&{rust}, {v});\n")
                }
                _ => {
                    let c = self.closure("", |em| Ok(format!("Ok({})", em.strict(&b.value)?)))?;
                    format!("nix::init_thunk(&{rust}, {c});\n")
                }
            };
            inits.push_str(&init);
        }
        stmts.push_str(&pre);
        stmts.push_str(&inits);
        Ok(declared)
    }

    // ---- selection ----------------------------------------------------------

    fn select(&mut self, subject: &Expr, path: &[AttrName], fallback: Option<&Expr>) -> R {
        // `builtins.x` on the global builtins is the builtin itself.
        if let (ExprKind::Var(v), None) = (&subject.kind, fallback) {
            if v == "builtins" && matches!(self.resolve("builtins"), Resolution::Global) {
                if let Some(first) = path[0].static_name() {
                    if arity_of(first).is_some() {
                        let head = format!("nix::builtins::get({})", lit(first));
                        if path.len() == 1 {
                            return Ok(head);
                        }
                        let p = self.attr_path(&path[1..])?;
                        return Ok(format!("nix::sel(&{head}, &[{p}])?"));
                    }
                }
            }
        }
        let s = self.operand(subject)?;
        let p = self.attr_path(path)?;
        match fallback {
            Some(f) => {
                let d = self.strict(f)?;
                Ok(format!("nix::sel_or(&{s}, &[{p}], || Ok({d}))?"))
            }
            None => Ok(format!("nix::sel(&{s}, &[{p}])?")),
        }
    }

    fn attr_path(&mut self, path: &[AttrName]) -> R {
        let mut parts = Vec::new();
        for a in path {
            parts.push(match a {
                AttrName::Static { name, .. } => format!("nix::k({})", lit(name)),
                AttrName::Dynamic { expr, .. } => format!("nix::key(&{})?", self.strict(expr)?),
            });
        }
        Ok(parts.join(", "))
    }

    // ---- functions ----------------------------------------------------------

    fn lambda(&mut self, param: Option<&str>, formals: Option<&Formals>, body: &Expr) -> R {
        let Some(formals) = formals else {
            let param = param.expect("a lambda has a parameter or formals");
            return self.closure_lambda(param, body);
        };
        self.formals_count += 1;
        let spec = format!("FORMALS_{}", self.formals_count);
        let args: Vec<String> = formals
            .entries
            .iter()
            .map(|f| {
                format!(
                    "({}, {}, {}, {})",
                    lit(&f.name),
                    f.fallback.is_some(),
                    f.pos.line,
                    f.pos.column
                )
            })
            .collect();
        self.statics.push(format!(
            "static {spec}: nix::Formals = nix::Formals {{ file: FILE, args: &[{}], ellipsis: {} }};",
            args.join(", "),
            formals.ellipsis
        ));
        // The argument and everything the entry binds belong to the
        // closure, so its frame starts at their scope.
        self.push_scope();
        self.frames.push((self.scopes.len() - 1, BTreeSet::new()));
        let arg = self.temp("arg");
        let r = {
            let em = &mut *self;
            let r = (|| {
                let set = em.temp("args");
                let mut stmts = format!("let {set} = nix::formals(&{arg}, &{spec})?;\n");
                if let Some(p) = param {
                    let whole = em.declare(p, false);
                    stmts.push_str(&format!("let {whole} = {arg}.clone();\n"));
                }
                // Declare every formal before emitting defaults, which may
                // refer to one another and to the @-bound argument.
                let mut defaults = Vec::new();
                for f in &formals.entries {
                    let v = em.declare(&f.name, false);
                    match &f.fallback {
                        None => stmts
                            .push_str(&format!("let {v} = nix::arg(&{set}, {})?;\n", lit(&f.name))),
                        Some(d) => {
                            stmts.push_str(&format!("let {v} = nix::blank();\n"));
                            defaults.push((f, d, v));
                        }
                    }
                }
                for (f, d, v) in defaults {
                    let c = em.closure("", |em| Ok(format!("Ok({})", em.strict(d)?)))?;
                    stmts.push_str(&format!(
                        "match {set}.get({}) {{ Some(j_v) => nix::init_value(&{v}, j_v.clone()), None => nix::init_thunk(&{v}, {c}) }}\n",
                        lit(&f.name)
                    ));
                }
                let b = em.strict(body)?;
                Ok(format!("{{\n{stmts}Ok({b})\n}}"))
            })();
            r
        };
        let (_, caps) = self.frames.pop().unwrap();
        self.pop_scope();
        let head = format!("move |{arg}: nix::Value| {}", r?);
        Ok(format!(
            "nix::lambda_formals(&{spec}, {})",
            with_clones(&caps, head)
        ))
    }

    fn closure_lambda(&mut self, param: &str, body: &Expr) -> R {
        self.push_scope();
        let r = self.closure_with_param(param, body);
        self.pop_scope();
        Ok(format!("nix::lambda({})", r?))
    }

    fn closure_with_param(&mut self, param: &str, body: &Expr) -> R {
        // The parameter belongs to the closure, so it is declared inside
        // the closure's frame.
        self.frames.push((self.scopes.len() - 1, BTreeSet::new()));
        let p = self.declare(param, false);
        let b = self.strict(body);
        let (_, mut caps) = self.frames.pop().unwrap();
        caps.remove(&p);
        Ok(with_clones(
            &caps,
            format!("move |{p}: nix::Value| Ok({})", b?),
        ))
    }

    // ---- application --------------------------------------------------------

    fn call(&mut self, e: &Expr) -> R {
        // Flatten `f a b c`.
        let mut args: Vec<&Expr> = Vec::new();
        let mut head = e;
        while let ExprKind::Call { func, arg } = &head.kind {
            args.push(arg);
            head = func;
        }
        args.reverse();
        if let Some(builtin) = self.builtin_head(head) {
            if let Some(arity) = arity_of(builtin) {
                if arity > 0 && builtin != "derivation" && args.len() >= arity {
                    if builtin == "import" {
                        self.note_import(args[0]);
                    }
                    let direct = args[..arity]
                        .iter()
                        .map(|a| self.lazy(a))
                        .collect::<Result<Vec<_>, _>>()?;
                    let callee = format!(
                        "nix::b::{}(&[{}])?",
                        rust_fn_name(builtin),
                        direct.join(", ")
                    );
                    if args.len() == arity {
                        return Ok(callee);
                    }
                    let rest = args[arity..]
                        .iter()
                        .map(|a| self.lazy(a))
                        .collect::<Result<Vec<_>, _>>()?;
                    return Ok(format!("nix::app(&{callee}, &[{}])?", rest.join(", ")));
                }
            }
        }
        let f = self.operand(head)?;
        let rendered = args
            .iter()
            .map(|a| self.lazy(a))
            .collect::<Result<Vec<_>, _>>()?;
        Ok(format!("nix::app(&{f}, &[{}])?", rendered.join(", ")))
    }

    // `import ./x.nix` with a literal path: the file must be compiled into
    // the program too.
    fn note_import(&mut self, arg: &Expr) {
        let ExprKind::Path(anchor, parts) = &arg.kind else {
            return;
        };
        let Some(text) = all_literal(parts) else {
            return;
        };
        self.note_path(*anchor, text);
    }

    // A file a literal path names, which an import may load: compiled too.
    fn note_path(&mut self, anchor: PathAnchor, text: String) {
        let p = match anchor {
            PathAnchor::Relative => format!("{}/{text}", self.dir),
            PathAnchor::Absolute => text,
            _ => return,
        };
        self.imports.push(p);
    }

    // The builtin a call head denotes statically: a global like `map`, or
    // `builtins.map` on the unshadowed `builtins`.
    fn builtin_head<'a>(&self, head: &'a Expr) -> Option<&'a str> {
        match &head.kind {
            ExprKind::Var(name) => {
                if !matches!(self.resolve(name), Resolution::Global) {
                    return None;
                }
                global_builtin(name)
            }
            ExprKind::Select {
                subject,
                path,
                fallback: None,
            } if path.len() == 1 => {
                let ExprKind::Var(v) = &subject.kind else {
                    return None;
                };
                if v != "builtins" || !matches!(self.resolve("builtins"), Resolution::Global) {
                    return None;
                }
                let name = path[0].static_name()?;
                arity_of(name).map(|_| name)
            }
            _ => None,
        }
    }

    // ---- operators ----------------------------------------------------------

    fn binary(&mut self, op: BinOp, l: &Expr, r: &Expr) -> R {
        let call = |em: &mut Self, f: &str| -> R {
            let a = em.operand(l)?;
            let b = em.operand(r)?;
            Ok(format!("nix::{f}(&{a}, &{b})?"))
        };
        match op {
            BinOp::And | BinOp::Or | BinOp::Impl => {
                let a = self.operand(l)?;
                let b = self.operand(r)?;
                Ok(match op {
                    BinOp::And => format!("nix::bool(nix::as_bool(&{a})? && nix::as_bool(&{b})?)"),
                    BinOp::Or => format!("nix::bool(nix::as_bool(&{a})? || nix::as_bool(&{b})?)"),
                    _ => format!("nix::bool(!nix::as_bool(&{a})? || nix::as_bool(&{b})?)"),
                })
            }
            BinOp::Eq => call(self, "op_eq"),
            BinOp::Ne => call(self, "op_ne"),
            BinOp::Lt => call(self, "op_lt"),
            // parser.y desugars `a > b` to `__lessThan b a` and `a <= b`
            // to `!(__lessThan b a)`, so the right operand goes first.
            BinOp::Gt | BinOp::Le => {
                let b = self.operand(r)?;
                let a = self.operand(l)?;
                let f = if op == BinOp::Gt { "op_lt" } else { "op_ge" };
                Ok(format!("nix::{f}(&{b}, &{a})?"))
            }
            BinOp::Ge => call(self, "op_ge"),
            BinOp::Update => call(self, "update"),
            BinOp::Concat => call(self, "concat"),
            BinOp::Add => call(self, "add"),
            BinOp::Sub => call(self, "sub"),
            BinOp::Mul => call(self, "mul"),
            BinOp::Div => call(self, "div"),
            BinOp::PipeRight => {
                let f = self.operand(r)?;
                let x = self.lazy(l)?;
                Ok(format!("nix::app(&{f}, &[{x}])?"))
            }
            BinOp::PipeLeft => {
                let f = self.operand(l)?;
                let x = self.lazy(r)?;
                Ok(format!("nix::app(&{f}, &[{x}])?"))
            }
        }
    }
}

// A `move` closure preceded by clones of the variables it captures.
fn with_clones(caps: &BTreeSet<String>, closure: String) -> String {
    if caps.is_empty() {
        return closure;
    }
    let clones: String = caps
        .iter()
        .map(|c| format!("let {c} = {c}.clone(); "))
        .collect();
    format!("{{ {clones}{closure} }}")
}

// The builtins.* name a free variable denotes, if it is one.
fn global_builtin(name: &str) -> Option<&str> {
    if is_global(name) && arity_of(name).is_some() {
        return Some(name);
    }
    let stripped = name.strip_prefix("__")?;
    arity_of(stripped).map(|_| stripped)
}

// Whether a binding's value is a literal that needs nothing else.
fn is_literal(e: &Expr) -> bool {
    match &e.kind {
        ExprKind::Int(_) | ExprKind::Float(_) => true,
        ExprKind::Str(parts) => all_literal(parts).is_some(),
        _ => false,
    }
}

// A float literal must read as a float: `1.0`, never `1`.
fn float_literal(f: f64) -> String {
    if f.is_infinite() {
        return "nix::float(f64::INFINITY)".into();
    }
    format!("nix::float({f:?})")
}
